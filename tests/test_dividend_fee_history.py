def test_unknown_currency_and_exact_int64_account_versions_are_retained(
    engine: Engine, book: dict[str, Any]
) -> None:
    maximum, large = 9223372036854775807, 9007199254740993
    with unit_of_work(engine, write=True) as con:
        con.exec_driver_sql(
            "UPDATE accounts SET version=? WHERE id=?", (maximum, str(book["account_id"]))
        )
        con.exec_driver_sql(
            "UPDATE brokers SET version=? WHERE id=?", (large, str(book["broker_id"]))
        )
    updated = {**book, "account_version": maximum, "broker_version": large}
