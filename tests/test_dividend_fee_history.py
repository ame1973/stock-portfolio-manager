@pytest.mark.parametrize(
    "field,value",
    [
        ("owner_id", str(OTHER)),
        ("event_id", str(uuid4())),
        ("revision_id", str(uuid4())),
        ("revision_no", 2),
        ("account_id", str(uuid4())),
        ("retained_portfolio_owner", str(OTHER)),
        ("retained_broker_owner", str(OTHER)),
        ("account_version", 2),
        ("retained_broker_version", 0),
        ("created_at", "2000-01-01T00:00:00.000000Z"),
        ("fee_micro", 0.3),
        ("fee_micro", -1),
        ("fee_currency", "CNY"),
        ("effective_from", "2026-02-30"),
        ("previous_id", str(uuid4())),
        ("fee_status", "UNKNOWN"),
        ("request_id", "private-invalid"),
        ("audit_id", str(uuid4())),
    ],
)
def test_corrupt_retained_rows_fail_closed_without_disclosing_private_data(
    engine: Engine, book: dict[str, Any], field: str, value: Any
) -> None:
    append_setting(engine, book)
    before = database_snapshot(engine)
    event = book["event"]
    with unit_of_work(engine) as con:
        execute = con.execute

        def corrupt(statement: Any, parameters: Any = None, **kwargs: Any) -> Any:
            result = execute(statement, parameters, **kwargs)
            if "SELECT f.*,p.owner_id AS retained_portfolio_owner" in str(statement):
                rows = [dict(row) for row in result.mappings()]
                assert len(rows) == 1
                rows[0][field] = value
                replacement = MagicMock()
                replacement.mappings.return_value = rows
                return replacement
            return result

        with (
            patch.object(con, "execute", side_effect=corrupt),
            pytest.raises(
                fees.FeeSettingError, match="^DIVIDEND_FEE_HISTORY_UNAVAILABLE$"
            ) as error,
        ):
            fees.history(con, OWNER, event.event_id, event.revision_id, 1, book["account_id"])
        assert "private-invalid" not in str(error.value) and REASON not in str(error.value)
    assert database_snapshot(engine) == before


def test_one_wal_snapshot_cannot_mix_old_and_new_fee_heads(
    engine: Engine, book: dict[str, Any]
) -> None:
    first = append_setting(engine, book)
    event = book["event"]
    with unit_of_work(engine) as reader:
        args = (reader, OWNER, event.event_id, event.revision_id, 1, book["account_id"])
        original = fees.history(*args)
        assert original is not None and len(original) == 1
        with ThreadPoolExecutor(max_workers=1) as pool:
            second = pool.submit(append_setting, engine, book, previous=first, fee_micro=1).result(
                timeout=10
            )
        assert fees.history(*args) == original
    assert [str(item.id) for item in history(engine, book)] == [first["id"], second["id"]]


