# This independent contract is deliberately not generated by the production reader.
AUDIT_FIELDS = (
    "id",
    "owner_id",
    "event_id",
    "revision_id",
    "revision_no",
    "portfolio_id",
    "account_id",
    "broker_id",
    "account_version",
    "broker_version",
    "setting_no",
    "previous_id",
    "effective_from",
    "fee_status",
    "fee_micro",
    "fee_currency",
    "request_id",
    "created_at",
)


def payload(row: dict[str, Any]) -> dict[str, Any]:
    return {
        **{key: row[key] for key in AUDIT_FIELDS},
        "reason_sha256": digest(canonical(REASON)),
        "scope": "OWNER_ESTIMATE_ONLY",
    }


def append_setting(
    engine: Engine,
    book: dict[str, Any],
    *,
    previous: dict[str, Any] | None = None,
    audit_delay: timedelta = timedelta(0),
    **changes: Any,
) -> dict[str, Any]:
    event = book["event"]
    created = datetime.now(UTC)
    row: dict[str, Any] = {
        "id": str(uuid4()),
        "owner_id": str(OWNER),
        "event_id": str(event.event_id),
        "revision_id": str(event.revision_id),
        "revision_no": event.revision_no,
        "portfolio_id": str(book["portfolio_id"]),
        "account_id": str(book["account_id"]),
        "broker_id": str(book["broker_id"]),
        "account_version": book["account_version"],
        "broker_version": book["broker_version"],
        "setting_no": 1 if previous is None else previous["setting_no"] + 1,
        "previous_id": None if previous is None else previous["id"],
        "effective_from": "2026-01-01",
        "fee_status": "ESTIMATED",
        "fee_micro": 0,
        "fee_currency": "HKD",
        "request_id": str(uuid4()),
        "created_at": stamp(created),
        **changes,
    }
    with unit_of_work(engine, write=True) as con:
        with patch("spm_api.audit.now", return_value=created + audit_delay):
            audit(
                con,
                str(OWNER),
                "dividend_fee_setting",
                row["id"],
                "DIVIDEND_FEE_SETTING_RECORDED",
                request_id=row["request_id"],
                before=payload(previous) if previous else None,
                after=payload(row),
                reason=REASON,
            )
        row["audit_id"] = con.exec_driver_sql(
            "SELECT id FROM audit_events WHERE entity_type='dividend_fee_setting' AND entity_id=?",
            (row["id"],),
        ).scalar_one()
        insert(con, TABLE, row)
    return row


def history(engine: Engine, book: dict[str, Any], owner: UUID = OWNER) -> Any:
    event = book["event"]
    with unit_of_work(engine) as con:
        return fees.history(
            con, owner, event.event_id, event.revision_id, event.revision_no, book["account_id"]
        )


