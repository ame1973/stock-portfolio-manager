def test_history_remains_readable_across_account_moves_and_new_event_revisions(
    engine: Engine, book: dict[str, Any]
) -> None:
    original = append_setting(engine, book)
    destination = account_scope(engine)
    with unit_of_work(engine, write=True) as con:
        con.exec_driver_sql(
            "UPDATE accounts SET portfolio_id=?,broker_id=?,version=version+1 WHERE id=?",
            (
                str(destination["portfolio_id"]),
                str(destination["broker_id"]),
                str(book["account_id"]),
            ),
        )
    moved = {
        **book,
        "portfolio_id": destination["portfolio_id"],
        "broker_id": destination["broker_id"],
        "account_version": book["account_version"] + 1,
        "broker_version": destination["broker_version"],
    }
    second = append_setting(engine, moved, previous=original, fee_micro=1234567)
    successor = next_intent(book["event"], "VERIFY")
    submit(engine, successor, at=datetime.now(UTC))
    before = database_snapshot(engine)
    rows = history(engine, book)
    assert [str(item.id) for item in rows] == [original["id"], second["id"]]
    assert rows[0].portfolio_id != rows[1].portfolio_id
    assert rows[0].broker_id != rows[1].broker_id
    assert history(engine, {**moved, "event": successor}) == ()
    assert database_snapshot(engine) == before


def test_rejected_then_resolved_history_is_visible_but_never_an_economic_grant(
    engine: Engine, book: dict[str, Any]
) -> None:
    original = append_setting(engine, book)
    rejected = reject(engine, rejection_intent(book["event"]))
    before = database_snapshot(engine)
    rows = history(engine, book)
    assert str(rows[0].id) == original["id"]
    assert fees.select(rows, date(2026, 1, 8)).scope == "UNVERIFIED_FEE_SELECTION_ONLY"
    assert database_snapshot(engine) == before
    successor = next_intent(book["event"], "VERIFY", resolve_rejection_id=rejected.id)
    submit(engine, successor, at=datetime.now(UTC))
    before = database_snapshot(engine)
    assert history(engine, book) == rows
    assert history(engine, {**book, "event": successor}) == ()
    assert database_snapshot(engine) == before


