    assert str(record.id) == row["id"] and record.fee is None and record.fee_currency is None
    assert record.account_version == maximum and record.broker_version == large
    assert fees.select((record,), date(2026, 1, 8)).status == "UNKNOWN"
    assert database_snapshot(engine) == before


