def test_canonical_chain_preserves_zero_unknown_currency_and_backdated_head(
    engine: Engine, book: dict[str, Any]
) -> None:
    zero = append_setting(engine, book)
    unknown = append_setting(
        engine,
        book,
        previous=zero,
        effective_from="2026-03-01",
        fee_status="UNKNOWN",
        fee_micro=None,
        fee_currency="USD",
    )
    maximum = append_setting(
        engine,
        book,
        previous=unknown,
        effective_from="2026-01-01",
        fee_micro=9223372036854775807,
        fee_currency="USD",
    )
    before = database_snapshot(engine)
    rows = history(engine, book)
    assert len(rows) == 3
    assert rows[0].fee == "0.000000" and rows[0].fee_currency == "HKD"
    assert rows[1].fee is None and rows[1].fee_currency == "USD"
    assert rows[2].fee == "9223372036854.775807"
    assert [str(item.id) for item in rows] == [zero["id"], unknown["id"], maximum["id"]]
    assert fees.select(rows, date(2025, 12, 31)).status == "MISSING"
    chosen = fees.select(rows, date(2026, 1, 8))
    assert chosen.selected == rows[2] and chosen.head_id == rows[2].id
    assert fees.select(rows[:2], date(2026, 1, 8)).selected == rows[0]
    assert fees.select(rows, date(2026, 3, 1)).status == "UNKNOWN"
    assert chosen.scope == "UNVERIFIED_FEE_SELECTION_ONLY"
    assert REASON not in repr(rows[2]) and rows[2].fee not in repr(rows[2])
    assert database_snapshot(engine) == before


def test_missing_foreign_mismatched_and_invalid_scopes_fail_without_zero(
    engine: Engine, book: dict[str, Any]
) -> None:
    event = book["event"]
    _, foreign = owned_account(engine, OTHER)
    before = database_snapshot(engine)
    with unit_of_work(engine) as con:
        args = (
            con,
            OWNER,
            event.event_id,
            event.revision_id,
            event.revision_no,
            book["account_id"],
        )
        assert fees.history(*args) == ()
        assert fees.history(con, OTHER, *args[2:]) is None
        assert fees.history(con, OWNER, uuid4(), *args[3:]) is None
        assert fees.history(con, OWNER, event.event_id, uuid4(), 1, book["account_id"]) is None
        assert (
            fees.history(con, OWNER, event.event_id, event.revision_id, 2, book["account_id"])
            is None
        )
        assert fees.history(con, OWNER, event.event_id, event.revision_id, 1, UUID(foreign)) is None
        bad_versions: tuple[Any, ...] = (True, 0, -1, 2147483648, "1")
        for bad in bad_versions:
            with pytest.raises(fees.FeeSettingError, match="^INVALID_DIVIDEND_FEE_SCOPE$"):
                fees.history(con, OWNER, event.event_id, event.revision_id, bad, book["account_id"])
    with (
        engine.connect() as con,
        pytest.raises(fees.FeeSettingError, match="^INVALID_DIVIDEND_FEE_SCOPE$"),
    ):
        fees.history(con, OWNER, event.event_id, event.revision_id, 1, book["account_id"])
    assert database_snapshot(engine) == before


